# Mastering Prompt Templates in LangChain

from langchain_core.prompts import PromptTemplate, ChatPromptTemplate

# -------------------- Task 1 --------------------

template1 = PromptTemplate(
    input_variables=["topic"],
    template="Explain {topic} in simple terms for beginners"
)

def explain_topic(topic):
    return template1.format(topic=topic)

print("Task 1 Output:")
print(explain_topic("Artificial Intelligence"))


# -------------------- Task 2 --------------------

template2 = PromptTemplate(
    input_variables=["topic", "audience", "tone"],
    template="Explain {topic} for {audience} in a {tone} tone"
)

print("\nTask 2 Output:")
print(template2.format(topic="AI", audience="beginners", tone="friendly"))
print(template2.format(topic="Python", audience="kids", tone="fun"))
