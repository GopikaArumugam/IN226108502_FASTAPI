# -------------------- Task 4 --------------------

chat_template = ChatPromptTemplate.from_messages([
    ("system", "You are a {role}"),
    ("user", "Explain {topic}")
])

def generate_chat(role, topic):
    return chat_template.format_messages(role=role, topic=topic)

print("\nTask 4 Output:")
messages = generate_chat("teacher", "Neural Networks")
for m in messages:
    print(m)


# -------------------- Task 5 --------------------

def validate_inputs(audience, tone):
    valid_audience = ["beginner", "intermediate", "expert"]
    valid_tone = ["formal", "casual", "fun"]

    if audience not in valid_audience:
        audience = "beginner"

    if tone not in valid_tone:
        tone = "formal"
    return audience, tone
print("\nTask 5 Output:")
print(validate_inputs("kids", "friendly"))
# -------------------- Task 6 --------------------
styles = {
    "teaching": "Explain {topic} for {audience} in a {tone} teaching style",
    "interview": "Ask interview questions about {topic} for {audience} in a {tone} tone",
    "storytelling": "Explain {topic} for {audience} in a {tone} storytelling style"
}
def generate_prompt(topic, audience, tone, style):
    audience, tone = validate_inputs(audience, tone)

    template = PromptTemplate(
        input_variables=["topic", "audience", "tone"],
        template=styles[style]
    )

    return template.format(topic=topic, audience=audience, tone=tone)

print("\nTask 6 Output:")
print(generate_prompt("Neural Networks", "beginner", "fun", "storytelling"))
# -------------------- Task 7 -------------------
